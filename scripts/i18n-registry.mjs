#!/usr/bin/env node
/**
 * Generates src/lib/i18n/registry.ts from the JSON catalogues in
 * src/lib/i18n/messages/{locale}/{namespace}.json. Run after adding a
 * namespace: `npm run i18n:registry` (tests fail when it is out of date).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '../src/lib/i18n')
const dir = path.join(root, 'messages')
const namespaces = readdirSync(path.join(dir, 'en'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -5))
  .sort()
const locales = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()

const id = (ns) => ns.replace(/-(\w)/g, (_, c) => c.toUpperCase())
const lines = [
  '// Generated by scripts/i18n-registry.mjs. Do not edit by hand.',
  "import type { Locale } from './config'",
  '',
  ...namespaces.map((ns) => `import type ${id(ns)} from './messages/en/${ns}.json'`),
  '',
  'export type Catalogues = {',
  ...namespaces.map((ns) => `  '${ns}': typeof ${id(ns)}`),
  '}',
  'export type Namespace = keyof Catalogues',
  '',
  `export const NAMESPACES = ${JSON.stringify(namespaces)} as const satisfies readonly Namespace[]`,
  '',
  'type Loader = () => Promise<{ default: unknown }>',
  '',
  '/** Lazy loaders: a catalogue is only read when a page needs it. */',
  'export const loaders: Partial<Record<Locale, Partial<Record<Namespace, Loader>>>> = {',
]
for (const locale of locales) {
  const have = new Set(
    readdirSync(path.join(dir, locale))
      .filter((f) => f.endsWith('.json'))
      .map((f) => f.slice(0, -5)),
  )
  lines.push(`  ${locale}: {`)
  for (const ns of namespaces) {
    if (have.has(ns)) lines.push(`    '${ns}': () => import('./messages/${locale}/${ns}.json'),`)
  }
  lines.push('  },')
}
lines.push('}', '')
const out = lines.join('\n')
const file = path.join(root, 'registry.ts')
let prev = ''
try {
  prev = readFileSync(file, 'utf8')
} catch {}
if (process.argv.includes('--check')) {
  if (prev !== out) {
    console.error('src/lib/i18n/registry.ts is out of date. Run: npm run i18n:registry')
    process.exit(1)
  }
} else if (prev !== out) {
  writeFileSync(file, out)
  console.log(`registry: ${namespaces.length} namespaces × ${locales.length} locales`)
}
